import Foundation
import VitekEngine

// Writes Sources/VitekEngine/EnglishWordList.swift: the everyday English words below, each checked
// against an English word list, whose Telex keys the engine would turn into a Vietnamese syllable
// with a tone while ending on a plain letter (`test` → tét).
//
// The word list only finds the candidates; which ones ship is chosen by hand, in `everyday`. Rare
// English words stay out because each listed word takes a reading away from Vietnamese typists who
// put the tone in mid-word. Words that only gain a vowel mark (`teen` → tên, `own` → ơn) never
// qualify: Telex typists add those marks as they type the vowel, so Vietnamese is the likely intent.
//
//   swift run vitek-wordlist /usr/share/dict/web2 > Sources/VitekEngine/EnglishWordList.swift

guard CommandLine.arguments.count == 2,
      let source = try? String(contentsOfFile: CommandLine.arguments[1], encoding: .utf8)
else {
    FileHandle.standardError.write(Data("usage: vitek-wordlist <word list>\n".utf8))
    exit(1)
}

let options = EngineOptions(keepEnglishWords: false)
/// Telex keys that mark rather than spell; a word ending on one is never kept as English.
let markKeys = Set("sfrxjzaeowd".utf8)
/// Combining grave, acute, tilde, hook above and dot below.
let toneMarks: Set<Unicode.Scalar> = ["\u{300}", "\u{301}", "\u{303}", "\u{309}", "\u{323}"]
let everyday: Set<String> = [
    "arm", "barn", "beset", "best", "boast", "boost", "born", "boron", "bosom", "burn",
    "burst", "bury", "bust", "busy", "cast", "charm", "chary", "chasm", "chest", "chosen",
    "churn", "coast", "corn", "corset", "cost", "cusp", "darn", "didst", "dorm", "durst",
    "dust", "gasp", "gist", "gust", "harm", "hasp", "hoary", "horn", "host", "ism",
    "kirsch", "last", "lest", "lisp", "list", "lorn", "lost", "lust", "mary", "mast",
    "mist", "moray", "morn", "moron", "most", "must", "nary", "nest", "nori", "norm",
    "orang", "oxen", "past", "perm", "pest", "post", "quasi", "quest", "rasp", "reset",
    "rest", "roast", "roost", "rosary", "rust", "sari", "tarn", "taxi", "term", "tern",
    "test", "thirst", "thorn", "toast", "torn", "trust", "turn", "urn", "vary", "vast",
    "vest",
]
var conflicts = Set<String>()
for line in source.split(whereSeparator: \.isNewline) {
    let word = String(line)
    guard word.count >= 2, word.utf8.allSatisfy({ (UInt8(ascii: "a")...UInt8(ascii: "z")).contains($0) }),
          let last = word.utf8.last, !markKeys.contains(last)
    else { continue }
    var engine = VitekEngine(options: options)
    guard word.allSatisfy({ engine.type($0) }), let finished = engine.finish(),
          let vietnamese = finished.vietnamese, finished.text != word,
          vietnamese.decomposedStringWithCanonicalMapping.unicodeScalars.contains(where: toneMarks.contains)
    else { continue }
    conflicts.insert(word)
}

print("""
// Generated by `swift run vitek-wordlist /usr/share/dict/web2`. Do not edit.
// Source: Webster's Second International (1934), public domain; see SOURCES.md.
extension EnglishWords {
    static let list = \"\"\"
""")
for word in everyday.subtracting(conflicts).sorted() {
    FileHandle.standardError.write(Data("vitek-wordlist: \(word) is not a conflict any more, left out\n".utf8))
}
for word in conflicts.intersection(everyday).sorted() { print("    " + word) }
print("""
    \"\"\"
}
""")
